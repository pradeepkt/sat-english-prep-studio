import type { ChoiceId, Difficulty, Domain, SubSkill } from "@/lib/labels"

export type BankQuestion = {
  sourceName: string
  domain: Domain
  subSkill: SubSkill
  difficulty: Difficulty
  passage: string
  prompt: string
  options: Array<{ id: ChoiceId; text: string }>
  correctOption: ChoiceId
  staticRationale: string
}

const SOURCE = "HighSchoolLearner Original Bank"

function item(
  domain: Domain,
  subSkill: SubSkill,
  difficulty: Difficulty,
  passage: string,
  prompt: string,
  options: [string, string, string, string],
  correct: ChoiceId,
  rationale: string,
): BankQuestion {
  const ids: ChoiceId[] = ["A", "B", "C", "D"]
  return {
    sourceName: SOURCE,
    domain,
    subSkill,
    difficulty,
    passage,
    prompt,
    options: options.map((text, index) => ({ id: ids[index], text })),
    correctOption: correct,
    staticRationale: rationale,
  }
}

