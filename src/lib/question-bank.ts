function hashString(value: string) {
  let hash = 2166136261
  for (let i = 0; i < value.length; i += 1) {
    hash ^= value.charCodeAt(i)
    hash = Math.imul(hash, 16777619)
  }
  return hash >>> 0
}

function withUniquePrompts(questions: BankQuestion[]) {
  const counts = new Map<string, number>()
  for (const question of questions) {
    counts.set(question.prompt, (counts.get(question.prompt) ?? 0) + 1)
  }
  return questions.map((question) => {
    if ((counts.get(question.prompt) ?? 0) < 2) return question
    const snippet = question.passage.replace(/\s+/g, " ").trim().slice(0, 52)
    return {
      ...question,
      prompt: `${question.prompt} Consider the text that begins “${snippet}”.`,
    }
  })
}

function balanceChoices(question: BankQuestion): BankQuestion {
  const shift = hashString(question.passage) % 4
  if (shift === 0) return question
  const ids: ChoiceId[] = ["A", "B", "C", "D"]
  const texts = question.options.map((option) => option.text)
  const oldIndex = Math.max(
    0,
    question.options.findIndex((option) => option.id === question.correctOption),
  )
  const rotated = texts.map((_, index) => texts[(index + shift) % texts.length])
  return {
    ...question,
    options: rotated.map((text, index) => ({ id: ids[index], text })),
    correctOption: ids[(oldIndex - shift + 4) % 4],
  }
}

export const questionBank: BankQuestion[] = withUniquePrompts(questionBankSeed).map(balanceChoices)

